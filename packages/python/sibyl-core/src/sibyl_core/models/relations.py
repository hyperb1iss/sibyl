"""The predicate vocabulary a writing agent may declare, and how to parse it.

Retrieval's graph expansion lane scores every hop by the edge's predicate.
This module owns both that score and hybrid traversal's multiplier so the
write vocabulary and both readers share one meaning for every predicate.

Direction convention
--------------------
Every declared edge runs FROM the memory being written TO the declared target,
because that is the direction the expansion walk follows. `_relation_target_hops`
selects `WHERE source_id IN $source_uuids` and returns `target_id`, so a seed
entity reaches the things it points at, and incoming edges are off by default.
The memory being written is therefore always the grammatical subject:

    remember("Postgres pooling, 2026 rewrite", ..., related_to=["supersedes:ep_0a1b"])

reads "this new memory supersedes ep_0a1b", and mints `new -SUPERSEDES-> ep_0a1b`.
The same convention already governs the one typed edge the system minted before
this module existed: reflection promotion writes
`_relationship(entity_id, superseded_id, RelationshipType.SUPERSEDES)`
(`sibyl_core/services/memory.py`), new row as source, replaced row as target.

The vocabulary
--------------
Closed, and deliberately small. Each entry names a `RelationshipType` that
already exists in the enum, so nothing here widens the schema; `relates_to.name`
is a plain string column and takes these without migration.

===============  ==================  ===================================================
Declaration      RelationshipType    Reads as (subject is the memory being written)
===============  ==================  ===================================================
supersedes       SUPERSEDES          replaces the target; the target is now stale
contradicts      CONTRADICTS         asserts the opposite of the target
requires         REQUIRES            depends on the target being true or done first
supports         SUPPORTS            is evidence for the target's claim or decision
decides          DECIDES             settles the question the target raises
===============  ==================  ===================================================

`caused_by` was considered and left out. No `CAUSED_BY` member exists in
`RelationshipType`, and the expansion weight table would score an invented one
at the 0.64 unknown default, which is exactly what an untyped `RELATED_TO`
already scores. It would cost a schema value and buy no retrieval signal.

`contradicts` is explicit at the fallback scores both readers used before the
canonical policy existed. The predicate keeps both endpoints recallable and
allows either endpoint to reach the other.

Unknown predicates are not an error
-----------------------------------
Anything that is not one of the five above is left alone: the whole string
stays the target id and the edge stays `RELATED_TO`, which is byte-for-byte
what every declaration did before this module existed. Entity ids generated by
`_generate_id` are `<type>_<hex12>` and never contain a colon, so a
colon-bearing string that does not lead with a vocabulary word is far more
likely to be an id shape we do not know about than a typo, and swallowing it
would lose the link entirely.

One ambiguity has no syntactic resolution. `Entity.id` is an unconstrained
string and restore validates whatever a backup carries, so an id spelled
`supersedes:legacy` is representable, and it parses as a declaration naming
`legacy` rather than as itself. Nothing in Sibyl mints an id of that shape, and
telling the two apart needs the store rather than the string, so the parser
takes the declaration reading and this is written down rather than guessed at.
"""

