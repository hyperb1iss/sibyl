@dataclass(frozen=True, slots=True)
class RelationDeclaration:
    """One parsed `related_to` entry.

    `target_id` is what the edge points at and what any existence or access
    check must run against; `declared` records whether the predicate came from
    the writer or is the untyped fallback.
    """

    target_id: str
    relationship_type: RelationshipType
    declared: bool

    @property
    def edge_slug(self) -> str:
        """Lowercase predicate for the deterministic relationship id."""
        return self.relationship_type.value.lower()


def _is_plausible_entity_id(value: str) -> bool:
    """Whether a string could be an entity id rather than prose or a fragment.

    Ids are opaque strings, so this cannot be exact. It rejects the shapes that
    are certainly not a single id: empty, internally separated, or carrying
    whitespace, which is what a mistyped declaration or a stray URL looks like.
    """
    if not value or RELATION_DECLARATION_SEPARATOR in value:
        return False
    return not any(character.isspace() for character in value)


def parse_relation_declaration(value: str) -> RelationDeclaration:
    """Split one `related_to` entry into a predicate and a target id.

    The prefix has to match a vocabulary word exactly and the remainder has to
    look like a single id, so `https://x/y` and `requires:a:b` stay whole
    rather than being torn into a predicate and a fragment.
    """
    text = str(value).strip()
    prefix, separator, remainder = text.partition(RELATION_DECLARATION_SEPARATOR)
    if not separator:
        return RelationDeclaration(text, RelationshipType.RELATED_TO, declared=False)

    relationship_type = DECLARABLE_RELATIONSHIP_PREDICATES.get(prefix.strip().lower())
    target_id = remainder.strip()
    if relationship_type is None or not _is_plausible_entity_id(target_id):
        return RelationDeclaration(text, RelationshipType.RELATED_TO, declared=False)
    return RelationDeclaration(target_id, relationship_type, declared=True)


def parse_relation_declarations(values: Iterable[str] | None) -> list[RelationDeclaration]:
    """Parse a whole `related_to` list, dropping blanks."""
    return [parse_relation_declaration(value) for value in values or () if str(value).strip()]


def declared_relation_targets(values: Sequence[str] | None) -> list[str]:
    """The entity ids a `related_to` list actually points at, predicates removed.

    Callers that validate targets or count links want the ids, not the
    declarations that carry them.
    """
    return [declaration.target_id for declaration in parse_relation_declarations(values)]
