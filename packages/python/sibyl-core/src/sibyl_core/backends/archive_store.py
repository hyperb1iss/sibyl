"""Write-once storage for organization backup archives.

An archive is written by whichever process ran the backup job (the API under
local coordination, a worker under Redis) and is later listed, downloaded and
deleted by any API replica, so every process of a deployment must open the
same store: a directory on a volume they all mount, or an S3 prefix
(:mod:`sibyl_core.backends.s3_archive_store`).

Both stores publish an archive once and atomically. A name that already holds
the same bytes reports "already there"; a name that holds different bytes is
an :class:`ArchiveConflict`, never an overwrite. A partly written archive is
never visible under its name: the directory store stages it in a hidden file
and publishes it with a hard link, and S3 shows nothing until PutObject or
CompleteMultipartUpload succeeds.

Archives carry secret material (content recovery keys among it), so names,
sizes and locations may be logged but archive bytes never are. Every storage
failure surfaces as :class:`ArchiveStoreUnavailable`, so callers answer an
outage the same way whichever store they run on.
"""

from __future__ import annotations

import errno
import hashlib
import json
import os
import re
import shutil
import stat
import tempfile
import time
from collections.abc import Generator, Iterator
from contextlib import contextmanager, suppress
from dataclasses import dataclass
from datetime import UTC, datetime
from pathlib import Path
from typing import BinaryIO, Protocol

import structlog

# Backup ids are generated by the API (backup_<org>_<time>_<nonce>); older
# ids and fixtures use other safe spellings, never path separators.
_BACKUP_ID = re.compile(r"[A-Za-z0-9][A-Za-z0-9_-]{0,127}")
_ARCHIVE_NAME = re.compile(r"sibyl_[A-Za-z0-9][A-Za-z0-9_-]{0,127}\.tar\.gz")
# Retention only ever considers archives the backup job names this way.
_RETAINED_NAME = re.compile(r"sibyl_backup_[A-Za-z0-9_-]{1,120}\.tar\.gz")
# One "bytes=first-last" range; anything else in a Range header is ignored.
_BYTE_RANGE = re.compile(r"\s*bytes\s*=\s*(\d*)\s*-\s*(\d*)\s*")
# A running backup's claim on a directory store's free space.
_RESERVATION_PREFIX = ".reserve-"
# Hidden working files a backup leaves in a directory store while it runs.
_STAGING_PREFIXES = (".staging-", ".partial-", ".probe-", _RESERVATION_PREFIX)
# A reservation untouched this long belongs to a backup that died.
_RESERVATION_LIFETIME_SECONDS = 24 * 60 * 60
# A claim file is a few dozen bytes; anything longer is not one of ours.
_MAX_CLAIM_BYTES = 4096
# Open a peer's claim without following a link or blocking on a FIFO.
_CLAIM_OPEN_FLAGS = (
    os.O_RDONLY
    | getattr(os, "O_NOFOLLOW", 0)
    | getattr(os, "O_NONBLOCK", 0)
    | getattr(os, "O_CLOEXEC", 0)
)

log = structlog.get_logger()
# link() answers these when the filesystem cannot make hard links at all.
_NO_HARD_LINKS = frozenset({errno.EPERM, errno.EOPNOTSUPP, errno.ENOTSUP, errno.ENOSYS})
CHUNK_SIZE = 1024 * 1024


class ArchiveStoreUnavailable(OSError):
    """The archive store failed or refused a request."""


class ArchiveStoreFull(ArchiveStoreUnavailable):
    """The archive volume lacks room for the next backup and its reserve."""


class ArchiveConflict(Exception):
    """The archive name already holds different bytes; nothing was replaced."""


class RangeNotSatisfiable(Exception):
    """A byte range starts past the end of the archive."""

    def __init__(self, total: int | None) -> None:
        super().__init__("Requested range is not satisfiable")
        self.total = total


def archive_name(backup_id: str) -> str:
    """The stored name of a backup's archive, refusing anything path-like."""
    if not _BACKUP_ID.fullmatch(backup_id):
        raise ValueError("Backup id is not a valid archive name")
    return f"sibyl_{backup_id}.tar.gz"


def backup_id_of(name: str) -> str:
    check_name(name)
    return name.removeprefix("sibyl_").removesuffix(".tar.gz")


def check_name(name: str) -> str:
    if not _ARCHIVE_NAME.fullmatch(name):
        raise ValueError("Not a backup archive name")
    return name


def retained_name(name: str) -> bool:
    """Whether retention may consider this stored name."""
    return bool(_RETAINED_NAME.fullmatch(name))


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(CHUNK_SIZE), b""):
            digest.update(chunk)
    return digest.hexdigest()


@dataclass(frozen=True)
class ByteRange:
    """One HTTP byte range: ``first-last``, ``first-``, or a suffix ``-last``.

    A suffix range has ``first`` None and asks for the final ``last`` bytes.
    """

    first: int | None
    last: int | None

    def resolve(self, total: int) -> tuple[int, int]:
        """The inclusive (start, end) this range covers in ``total`` bytes."""
        if self.first is None:
            length = self.last or 0
            if length <= 0 or total <= 0:
                raise RangeNotSatisfiable(total)
            return max(total - length, 0), total - 1
        if self.first >= total:
            raise RangeNotSatisfiable(total)
        end = total - 1 if self.last is None else min(self.last, total - 1)
        return self.first, end

    def header(self) -> str:
        first = "" if self.first is None else str(self.first)
        last = "" if self.last is None else str(self.last)
        return f"bytes={first}-{last}"


def parse_byte_range(header: str | None) -> ByteRange | None:
    """The single byte range a Range header asks for, or None to send it all.

    RFC 9110 lets a server ignore a Range header, and requires it to ignore a
    syntactically invalid one, so other units, several ranges and malformed
    specs all read as "the whole archive".
    """
    match = _BYTE_RANGE.fullmatch(header or "")
    if match is None:
        return None
    first, last = (int(value) if value else None for value in match.groups())
    if first is None and last is None:
        return None
    if first is not None and last is not None and last < first:
        return None
    return ByteRange(first, last)


@dataclass(frozen=True)
class ArchiveObject:
    """One published archive as a listing reports it."""

    name: str
    size: int
    modified: datetime


class ArchiveReader(Protocol):
    """An open archive, or one byte range of it, streamed in chunks.

    ``size`` is how many bytes ``chunks`` yields, ``start`` where they begin
    and ``total`` the whole archive's size. ``partial`` says whether those
    bytes are the requested range; a store may answer a range with the
    whole archive instead. ``sha256`` is the digest the store recorded at
    publish time, when it keeps one.
    """

    size: int
    start: int
    total: int
    partial: bool
    sha256: str | None

    def chunks(self) -> Iterator[bytes]: ...

    def close(self) -> None: ...


class ArchiveStore(Protocol):
    def ready(self) -> None:
        """Fail now, before a backup does its work, if archives cannot be published."""

    def reserve(self, holder: str, estimated_bytes: int) -> Reservation:
        """Claim room for one running backup, or fail now if it would not fit.

        Backups running at the same time on the same store count each
        other's claims. Release the reservation when the backup ends.
        """

    def staging_dir(self) -> Path | None:
        """Where a backup should assemble its archive; None means the system temp dir."""

    def location(self, name: str) -> str:
        """Where an archive lives, for records and logs (never a credential)."""

    def put_new(self, name: str, source: Path, *, sha256: str) -> bool:
        """Publish ``source`` under ``name`` once.

        Returns True when created and False when ``name`` already holds the
        same bytes (a retried write that landed). Raises ArchiveConflict when
        it holds different bytes.
        """

    def open(self, name: str, byte_range: ByteRange | None = None) -> ArchiveReader | None:
        """Stream a published archive, or None when there is none.

        Raises RangeNotSatisfiable when ``byte_range`` starts past its end.
        """

    def archives(self) -> list[ArchiveObject]:
        """Every published backup archive, in no particular order."""

    def delete(self, name: str) -> None:
        """Remove an archive; a missing one is already gone."""

    def sweep_stale(self, older_than: datetime) -> int:
        """Remove working files abandoned before ``older_than``; returns how many."""


def _fsync(path: Path) -> None:
    """Flush a file's data, or a directory's entries, to stable storage."""
    descriptor = os.open(path, os.O_RDONLY)
    try:
        os.fsync(descriptor)
    finally:
        os.close(descriptor)


def _mebibytes(count: int) -> str:
    if count < 1024 * 1024:
        return f"{count / 1024:.0f} KiB"
    return f"{count / (1024 * 1024):.0f} MiB"


class Reservation(Protocol):
    """One running backup's claim on its store's free space."""

    def track(self, staging: Path) -> None:
        """Name the staging directory whose bytes already count against the claim."""

    def require(self, additional_bytes: int) -> None:
        """Claim this much beyond what is staged, or fail if it would not fit."""

    def release(self) -> None:
        """Give the claim back; the backup is finished either way."""


class NoReservation:
    """A store with no shared volume to fill claims nothing."""

    def track(self, staging: Path) -> None:
        del staging

    def require(self, additional_bytes: int) -> None:
        del additional_bytes

    def release(self) -> None:
        return None


_IGNORED_CLAIMS: set[str] = set()


def _not_a_claim(path: str, reason: str) -> None:
    """Skip a .reserve-* entry no backup wrote, warning once per entry."""
    if path not in _IGNORED_CLAIMS:
        _IGNORED_CLAIMS.add(path)
        log.warning("backup_claim_ignored", path=path, reason=reason)


def _read_claim(entry: os.DirEntry[str]) -> dict | None:
    """A peer backup's claim, or None for anything that is not a regular claim file.

    Claims are read without following links and without blocking, and only
    up to a small cap, so a FIFO, a link to a device or an oversized file
    named like a claim cannot hang or exhaust every backup's space check.
    """
    try:
        if not entry.is_file(follow_symlinks=False):
            _not_a_claim(entry.path, "not a regular file")
            return None
        descriptor = os.open(entry.path, _CLAIM_OPEN_FLAGS)
    except FileNotFoundError:
        return None
    except OSError as error:
        _not_a_claim(entry.path, error.strerror or type(error).__name__)
        return None
    try:
        if not stat.S_ISREG(os.fstat(descriptor).st_mode):
            _not_a_claim(entry.path, "not a regular file")
            return None
        data = os.read(descriptor, _MAX_CLAIM_BYTES + 1)
    except OSError as error:
        _not_a_claim(entry.path, error.strerror or type(error).__name__)
        return None
    finally:
        os.close(descriptor)
    if len(data) > _MAX_CLAIM_BYTES:
        _not_a_claim(entry.path, "larger than any claim")
        return None
    try:
        payload = json.loads(data)
    except ValueError:
        # A claim being replaced is never torn (it is renamed into place),
        # so unparseable bytes are not a claim either.
        return None
    return payload if isinstance(payload, dict) else None


def _staged_bytes(directory: Path) -> int:
    """Bytes a staging directory holds now; a missing one holds nothing."""
    total = 0
    try:
        with os.scandir(directory) as entries:
            for entry in entries:
                try:
                    if entry.is_file(follow_symlinks=False):
                        total += entry.stat(follow_symlinks=False).st_size
                except FileNotFoundError:
                    continue
    except (FileNotFoundError, NotADirectoryError):
        return 0
    return total


class _DirectoryReservation:
    """A reservation file beside the archives, read by every other backup.

    The file names the bytes this backup will put on the volume and its
    staging directory. What it has already staged is on the disk, so the
    rest of the claim is the part other backups must leave free. Each
    backup writes its claim before it checks free space, so two backups
    starting together each see the other and neither overcommits; at worst
    both are refused and the next run goes ahead.
    """

    def __init__(self, store: DirectoryArchiveStore, holder: str) -> None:
        if not _BACKUP_ID.fullmatch(holder):
            raise ValueError("Reservation holder is not a valid backup id")
        self._store = store
        self._path = store.staging_dir() / f"{_RESERVATION_PREFIX}{holder}"
        self._staging: Path | None = None
        self._bytes = 0

    def _write(self) -> None:
        payload = {"bytes": self._bytes, "staging": self._staging.name if self._staging else ""}
        descriptor, partial = tempfile.mkstemp(
            prefix=f"{self._path.name}.tmp-", dir=self._path.parent
        )
        with os.fdopen(descriptor, "w", encoding="utf-8") as handle:
            json.dump(payload, handle)
        os.replace(partial, self._path)

    def claim(self, total_bytes: int) -> None:
        try:
            with self._store._refusals("a free-space check"):
                self._bytes = total_bytes
                self._write()
                staged = _staged_bytes(self._staging) if self._staging else 0
                self._store._check_room(max(total_bytes - staged, 0), own=self._path)
        except BaseException:
            # A claim that failed for any reason, a full volume or an I/O
            # error while checking, must not keep counting against others.
            # A failing cleanup must not hide why the claim failed.
            with suppress(OSError):
                self._path.unlink(missing_ok=True)
            raise

    def track(self, staging: Path) -> None:
        with self._store._refusals("a reservation"):
            self._staging = staging
            self._write()

    def require(self, additional_bytes: int) -> None:
        staged = _staged_bytes(self._staging) if self._staging else 0
        self.claim(staged + additional_bytes)

    def release(self) -> None:
        self._path.unlink(missing_ok=True)


class _FileReader:
    def __init__(
        self, handle: BinaryIO, *, start: int, size: int, total: int, partial: bool
    ) -> None:
        self._handle = handle
        self.start = start
        self.size = size
        self.total = total
        self.partial = partial
        self.sha256 = None

    def chunks(self) -> Iterator[bytes]:
        remaining = self.size
        try:
            while remaining > 0 and (chunk := self._handle.read(min(CHUNK_SIZE, remaining))):
                remaining -= len(chunk)
                yield chunk
        finally:
            self.close()

    def close(self) -> None:
        self._handle.close()


class DirectoryArchiveStore:
    """Archives as private files in one directory, published by hard link.

    Every process that writes or serves archives must mount the same
    directory; on Kubernetes that means one claim shared by API and worker,
    ReadWriteMany when replicas run on different nodes. ``reserve_bytes`` is
    kept free on that volume for its other writers (validation receipts share
    it by default), so a backup that would eat into it is refused up front.
    """

    def __init__(self, root: Path | str, *, reserve_bytes: int = 0) -> None:
        self._root = Path(root).expanduser()
        self._reserve_bytes = reserve_bytes

    @contextmanager
    def _refusals(self, action: str) -> Generator[None]:
        """Report any filesystem failure as the store being unavailable."""
        try:
            yield
        except ArchiveStoreUnavailable:
            raise
        except OSError as error:
            reason = error.strerror or type(error).__name__
            raise ArchiveStoreUnavailable(
                f"Backup archive directory {self._root} refused {action}: {reason}"
            ) from error

    def _no_hard_links(self) -> ArchiveStoreUnavailable:
        return ArchiveStoreUnavailable(
            f"Backup archive directory {self._root} is on a filesystem without hard links, "
            "which archives are published with so none is ever replaced or seen half "
            "written; use a POSIX volume or an S3 archive store"
        )

    def _link(self, source: Path, target: Path) -> None:
        try:
            os.link(source, target)
        except FileExistsError:
            raise
        except OSError as error:
            if error.errno in _NO_HARD_LINKS:
                raise self._no_hard_links() from error
            raise

    def _directory(self) -> Path:
        path = self._root.absolute()
        # Archives hold secrets: a new directory is private. An existing one
        # keeps its mode, so upgrading never breaks a working deployment.
        path.mkdir(mode=0o700, parents=True, exist_ok=True)
        return path

    def _path(self, name: str) -> Path:
        return self._directory() / check_name(name)

    def ready(self) -> None:
        """Create a probe and publish it by hard link, as a backup will."""
        with self._refusals("a readiness probe"):
            directory = self._directory()
            descriptor, name = tempfile.mkstemp(prefix=".probe-", dir=directory)
            os.close(descriptor)
            probe = Path(name)
            published = probe.with_name(f"{probe.name}.published")
            try:
                self._link(probe, published)
            finally:
                published.unlink(missing_ok=True)
                probe.unlink(missing_ok=True)

    def _claimed_by_others(self, own: Path) -> int:
        """Room other running backups have claimed and not yet staged."""
        directory = self._directory()
        claimed = 0
        stale_before = time.time() - _RESERVATION_LIFETIME_SECONDS
        with os.scandir(directory) as entries:
            for entry in entries:
                if not entry.name.startswith(_RESERVATION_PREFIX) or ".tmp-" in entry.name:
                    continue
                if entry.path == str(own):
                    continue
                try:
                    if entry.stat(follow_symlinks=False).st_mtime < stale_before:
                        continue
                except FileNotFoundError:
                    continue
                payload = _read_claim(entry)
                if payload is None:
                    continue
                try:
                    total = int(payload["bytes"])
                    staging = str(payload.get("staging") or "")
                except (KeyError, TypeError, ValueError):
                    continue
                # Only a staging directory beside the archives counts as staged.
                staged = (
                    _staged_bytes(directory / staging)
                    if staging.startswith(".staging-") and "/" not in staging
                    else 0
                )
                claimed += max(total - staged, 0)
        return claimed

    def _check_room(self, needed_bytes: int, *, own: Path) -> None:
        free = shutil.disk_usage(self._directory()).free
        others = self._claimed_by_others(own)
        if free < needed_bytes + others + self._reserve_bytes:
            held = f", other running backups hold {_mebibytes(others)}," if others else ""
            raise ArchiveStoreFull(
                f"Backup archive directory {self._root} has {_mebibytes(free)} free; this "
                f"backup needs about {_mebibytes(needed_bytes)}{held} plus "
                f"{_mebibytes(self._reserve_bytes)} kept free for other writers on the "
                "volume. Free space, shorten retention, or move archives to a dedicated "
                "volume or S3."
            )

    def reserve(self, holder: str, estimated_bytes: int) -> Reservation:
        reservation = _DirectoryReservation(self, holder)
        reservation.claim(estimated_bytes)
        return reservation

    def staging_dir(self) -> Path:
        with self._refusals("staging"):
            return self._directory()

    def location(self, name: str) -> str:
        with self._refusals("a lookup"):
            return str(self._path(name))

    def _stage_copy(self, source: Path, directory: Path) -> Path:
        descriptor, staged = tempfile.mkstemp(prefix=".partial-", dir=directory)
        try:
            with os.fdopen(descriptor, "wb") as output, source.open("rb") as handle:
                shutil.copyfileobj(handle, output, CHUNK_SIZE)
        except BaseException:
            Path(staged).unlink(missing_ok=True)
            raise
        return Path(staged)

    def put_new(self, name: str, source: Path, *, sha256: str) -> bool:
        with self._refusals("a publish"):
            target = self._path(name)
            staged: Path | None = None
            source.chmod(0o600)
            _fsync(source)
            try:
                try:
                    self._link(source, target)
                except FileExistsError:
                    raise
                except OSError as error:
                    if error.errno != errno.EXDEV:
                        raise
                    # Assembled on another filesystem: copy beside the target
                    # under a hidden name, then publish that copy by link.
                    staged = self._stage_copy(source, target.parent)
                    _fsync(staged)
                    self._link(staged, target)
            except FileExistsError:
                if sha256_file(target) != sha256:
                    raise ArchiveConflict(f"{name} already holds a different archive") from None
                return False
            finally:
                if staged is not None:
                    staged.unlink(missing_ok=True)
            _fsync(target.parent)
            return True

    def open(self, name: str, byte_range: ByteRange | None = None) -> ArchiveReader | None:
        with self._refusals("a read"):
            path = self._path(name)
            try:
                descriptor = os.open(path, os.O_RDONLY | getattr(os, "O_NOFOLLOW", 0))
            except FileNotFoundError:
                return None
            handle = os.fdopen(descriptor, "rb")
            try:
                total = os.fstat(handle.fileno()).st_size
                start, end = byte_range.resolve(total) if byte_range else (0, total - 1)
                handle.seek(start)
            except BaseException:
                handle.close()
                raise
            return _FileReader(
                handle,
                start=start,
                size=end - start + 1,
                total=total,
                partial=byte_range is not None,
            )

    def archives(self) -> list[ArchiveObject]:
        found: list[ArchiveObject] = []
        with self._refusals("a listing"), os.scandir(self._directory()) as entries:
            for entry in entries:
                if not retained_name(entry.name) or not entry.is_file(follow_symlinks=False):
                    continue
                try:
                    stat = entry.stat(follow_symlinks=False)
                except FileNotFoundError:
                    continue
                found.append(
                    ArchiveObject(
                        name=entry.name,
                        size=stat.st_size,
                        modified=datetime.fromtimestamp(stat.st_mtime, tz=UTC),
                    )
                )
        return found

    def delete(self, name: str) -> None:
        with self._refusals("a delete"):
            path = self._path(name)
            path.unlink(missing_ok=True)
            _fsync(path.parent)

    def sweep_stale(self, older_than: datetime) -> int:
        """Remove staging directories, partial copies and probes left by dead jobs.

        They hold plaintext export JSON on a durable volume. Anything touched
        since ``older_than`` may belong to a backup still running and stays.
        """
        cutoff = older_than.timestamp()
        removed = 0
        with self._refusals("a staging sweep"), os.scandir(self._directory()) as entries:
            for entry in entries:
                if not entry.name.startswith(_STAGING_PREFIXES):
                    continue
                try:
                    if _newest_mtime(entry) >= cutoff:
                        continue
                    if entry.is_dir(follow_symlinks=False):
                        shutil.rmtree(entry.path)
                    else:
                        os.unlink(entry.path)
                except FileNotFoundError:
                    continue
                removed += 1
        return removed


def _newest_mtime(entry: os.DirEntry[str]) -> float:
    """An entry's mtime, or for a directory the newest of it and its children."""
    newest = entry.stat(follow_symlinks=False).st_mtime
    if entry.is_dir(follow_symlinks=False):
        with os.scandir(entry.path) as children:
            for child in children:
                newest = max(newest, child.stat(follow_symlinks=False).st_mtime)
    return newest


